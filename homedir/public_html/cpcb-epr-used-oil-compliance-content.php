                    <!-- Frequently Asked Questions -->
                    <h2 class="gw-h2-title">Frequently Asked Questions (FAQ)</h2>
                    
                    <div class="gw-faq-card">
                        <h4>Q1: Is EPR registration mandatory for factories that generate used oil?</h4>
                        <p>Yes. Under the Hazardous and Other Wastes Rules, bulk industrial consumers generating used engine, gear, hydraulic, or transformer oils must register on the CPCB portal and route consignments strictly through authorized recyclers to obtain verified proof of disposal.</p>
                    </div>

                    <div class="gw-faq-card">
                        <h4>Q2: What is the penalty for selling used oil to informal or uncertified buyers?</h4>
                        <p>Selling hazardous used oil to unauthorized buyers violates the Environment (Protection) Act, 1986. Penalties include steep Environmental Compensation fines calculated on the volume of unmanifested waste, revocation of factory Consent to Operate (CTO), and legal liabilities.</p>
                    </div>

                    <div class="gw-faq-card">
                        <h4>Q3: How do EPR certificates differ from Form 10 manifests?</h4>
                        <p>A Form 10 manifest is a physical consignment document tracking movement from generator to recycler. An EPR certificate is a digital credit generated on the central CPCB portal confirming the waste was converted into reusable base oil via certified re-refining.</p>
                    </div>

                    <div class="gw-faq-card">
                        <h4>Q4: Can transformer oil and hydraulic oil be recycled under EPR?</h4>
                        <p>Yes. Used transformer oils, hydraulic fluids, gear oils, and spent turbine oils are classified as used oils and are fully eligible for recovery and EPR certificate generation.</p>
