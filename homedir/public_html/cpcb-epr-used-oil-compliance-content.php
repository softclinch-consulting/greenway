                    <!-- Section 3: 5 Non-Negotiable Requirements -->
                    <h2 class="gw-h2-title">3. The 5 Factory-Floor Compliance Requirements for Plant Heads</h2>
                    <p>
                        State Pollution Control Boards (such as TNPCB in Tamil Nadu) conduct targeted inspections in industrial corridors including Sriperumbudur, Oragadam, Hosur, Ambattur, and Coimbatore. Factories must verify compliance against five specific standards:
                    </p>

                    <div class="gw-checklist-grid">
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-shield"></i> 1. Secondary Containment</h4>
                            <p>Used oil must be stored on an impervious floor surrounded by a containment bund capable of holding 110% of the largest drum volume. Drums must be weather-protected and labeled "HAZARDOUS WASTE - USED OIL".</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-file-text-o"></i> 2. Form 10 Manifests</h4>
                            <p>Every consignment leaving your factory gate must be covered by a 7-copy Form 10 manifest detailing the waste category, volume, transporter details, and designated recycling plant.</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-truck"></i> 3. GPS Vacuum Tankers</h4>
                            <p>Evacuation must occur through authorized vacuum tankers with spill containment gear. Discharging into unverified trucks or informal scrap aggregators is an offense under the EPA Act.</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-ban"></i> 4. Zero Dilution Standard</h4>
                            <p>Never mix used lubricants with solvents, coolants, diesel, or general workshop refuse. Contamination drops the flash point and causes rejection at the re-refining lab.</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-qrcode"></i> 5. GST E-Invoiced Records</h4>
                            <p>All waste transactions and EPR credit certificates must be validated with GST-linked e-invoicing. Retain all signed manifests and test slips for a minimum of 5 years.</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-recycle"></i> 6. CPCB Credit Retirement</h4>
                            <p>Producers offset their annual recycling obligation by purchasing digital EPR certificates on the CPCB portal, ensuring transparent retirement from the national register.</p>
                        </div>
                    </div>

