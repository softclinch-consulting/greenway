                    <!-- Section 3: The 30-Day Blue Copy Trap -->
                    <h2 class="gw-h2-title">3. The 30-Day "Blue Copy" Trap: Why Audits Fail</h2>
                    <p>
                        The most common cause of non-compliance during TNPCB audits in Tamil Nadu industrial corridors (such as Sriperumbudur, Oragadam, Ambattur, and Ranipet) is the <strong>absence of matching Blue Copies</strong>.
                    </p>
