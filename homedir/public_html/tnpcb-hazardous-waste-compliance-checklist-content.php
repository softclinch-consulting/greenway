                    <!-- Section 3: CTO Renewal Dossier Checklist -->
                    <h2 class="gw-h2-title">3. The 9-Point Document Dossier for Consent to Operate (CTO) Renewal</h2>
                    <p>
                        When applying for CTO Renewal and Hazardous Waste Authorization via the TNPCB OCMMS portal, ensure these 9 mandatory documents are fully compiled:
                    </p>
                    <ol style="font-size:16px;color:var(--gw-text-muted);padding-left:22px;margin-bottom:30px;line-height:1.8;">
                        <li><strong>Duly Executed Covering Letter:</strong> Signed by the Factory Director or Occupier explaining operational capacity and waste profile.</li>
                        <li><strong>Copies of Previous Consents:</strong> Previous CTO orders under the Water and Air Acts, alongside the latest Hazardous Waste Authorization copy.</li>
                        <li><strong>Comprehensive Process Flow Diagram:</strong> Depicting material balances, input chemicals/lubricants, points of waste generation, and emission vents.</li>
                        <li><strong>Authorized Recycler Agreement:</strong> Valid, active tripartite or bilateral agreement with a TNPCB-authorized actual-user recycler (such as <em>Green Way Industries</em>).</li>
                        <li><strong>Form 10 Manifest Audit Register:</strong> Certified chronological ledger of all Copy 2 (Yellow) and matching Copy 6 (Blue) signed manifests for the preceding 12 months.</li>
                        <li><strong>Past Form 4 Annual Returns:</strong> Stamped acknowledgment copies of submitted Form 4 filings for the preceding 3 consecutive financial years.</li>
                        <li><strong>Site Layout Map of 90-Day Storage Shed:</strong> Scaled architectural plot drawing highlighting the exact geo-coordinates, bunding volume, and fire exits.</li>
                        <li><strong>Emergency Response Plan (ERP):</strong> Documented standard operating procedure for chemical spillages, tanker overflow, or storage area fires.</li>
                        <li><strong>Analysis Reports from TNPCB / NABL Labs:</strong> Latest environmental test reports for groundwater, ambient air quality, and representative waste samples.</li>
                    </ol>

                    <!-- Section 4: Top 6 Audit Red Flags -->
                    <h2 class="gw-h2-title">4. Top 6 Factory Floor Audit Violations That Trigger Show-Cause Notices</h2>
                    <p>
                        During field inspections, TNPCB environmental engineers look specifically for these recurring operational lapses:
                    </p>

                    <div class="gw-checklist-grid">
                        <div class="gw-checklist-card" style="border-top-color:#d32f2f;">
                            <h4><i class="fa fa-times-circle" style="color:#d32f2f;"></i> 1. Missing Blue Copies</h4>
                            <p>Yellow copies of Form 10 without their corresponding Blue Copy returned by the recycler within 30 days trigger immediate presumption of unauthorized dumping.</p>
                        </div>
                        <div class="gw-checklist-card" style="border-top-color:#d32f2f;">
                            <h4><i class="fa fa-times-circle" style="color:#d32f2f;"></i> 2. Mixing Oil with Coolant/Solvents</h4>
                            <p>Diluting used lubricating oil with machine coolants, solvents, or housekeeping wash water alters flash points and leads to lab rejections at re-refiners.</p>
                        </div>
                        <div class="gw-checklist-card" style="border-top-color:#d32f2f;">
                            <h4><i class="fa fa-times-circle" style="color:#d32f2f;"></i> 3. Breaching the 90-Day Limit</h4>
                            <p>Storing drums for more than 90 days without written board permission. Accumulation dates on barrel labels must verify zero over-aged inventory.</p>
                        </div>
                        <div class="gw-checklist-card" style="border-top-color:#d32f2f;">
                            <h4><i class="fa fa-times-circle" style="color:#d32f2f;"></i> 4. Broken or Unpaved Bunds</h4>
                            <p>Storage bays lacking bund containment or featuring unsealed floors allow trace petroleum hydrocarbons to leach into surrounding subsoil and groundwater.</p>
                        </div>
                        <div class="gw-checklist-card" style="border-top-color:#d32f2f;">
                            <h4><i class="fa fa-times-circle" style="color:#d32f2f;"></i> 5. Handover to Scrap Brokers</h4>
                            <p>Selling used oil or spent drums to unregistered local scrap buyers. Transactions without GST e-invoices and Form 10 are criminal environmental offenses.</p>
                        </div>
                        <div class="gw-checklist-card" style="border-top-color:#d32f2f;">
                            <h4><i class="fa fa-times-circle" style="color:#d32f2f;"></i> 6. Logbook vs Manifest Mismatches</h4>
                            <p>Any discrepancy between the net metric weight entered in Form 3 and the volume reported in annual Form 4 filings draws severe scrutiny.</p>
                        </div>
                    </div>

