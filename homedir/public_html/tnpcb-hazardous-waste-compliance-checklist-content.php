                    <!-- Frequently Asked Questions -->
                    <h2 class="gw-h2-title">Frequently Asked Questions (FAQ)</h2>
                    
                    <div class="gw-faq-card">
                        <h4>Q1: What is the 90-day hazardous waste storage rule under TNPCB regulations?</h4>
                        <p>Under Rule 8 of the Hazardous and Other Wastes Rules, an industrial occupier is legally permitted to store hazardous waste on-site for a maximum of 90 days. Before this period expires, the accumulated waste must be manifested and transferred to an authorized actual-user recycler or TSDF.</p>
                    </div>

                    <div class="gw-faq-card">
                        <h4>Q2: What is the difference between Form 3 and Form 4 under hazardous waste rules?</h4>
                        <p>Form 3 is an on-site, day-to-day register tracking daily generation, storage, and disposal of hazardous waste, which must be presented during unannounced TNPCB inspections. Form 4 is the annual compliance return compiled from Form 3 and Form 10 manifests, which must be submitted to TNPCB on or before June 30th of every year.</p>
                    </div>

                    <div class="gw-faq-card">
                        <h4>Q3: What secondary containment specifications are required for hazardous waste sheds?</h4>
                        <p>The storage shed must feature an impervious concrete floor with epoxy/acid-resistant coating, surrounded by a containment bund wall engineered to hold at least 110% volume of the largest drum or container stored, alongside dedicated spill kits and no rainwater drainage connection.</p>
                    </div>

                    <div class="gw-faq-card">
                        <h4>Q4: Can an industry renew its Consent to Operate (CTO) without a valid hazardous waste recycler agreement?</h4>
                        <p>No. TNPCB mandates a live, authenticated off-take agreement with an authorized recycler or TSDF, along with copies of past Form 10 manifests and Form 4 annual returns, as mandatory prerequisites for renewing Consent to Operate (CTO) and Hazardous Waste Authorization.</p>
                    </div>

                    <div class="gw-faq-card">
                        <h4>Q5: What are the penalties for exceeding the 90-day storage limit in Tamil Nadu?</h4>
                        <p>Exceeding the 90-day storage limit without written permission from TNPCB attracts daily Environmental Compensation fines under CPCB guidelines, issuance of show-cause notices under Section 33A of the Water Act and Section 31A of the Air Act, and potential disconnection of factory electricity and water supplies.</p>
