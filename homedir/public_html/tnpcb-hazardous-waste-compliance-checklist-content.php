                    <h1 style="color:var(--gw-deep);font-size:32px;font-weight:700;line-height:1.35;margin-bottom:20px;">
                        TNPCB Hazardous Waste Factory Audit Checklist: Consent to Operate (CTO) &amp; 90-Day Storage Compliance in Tamil Nadu
                    </h1>

                    <p style="font-size:17px;color:var(--gw-text-muted);margin-bottom:25px;">
                        Across key manufacturing hubs in Tamil Nadu—including <strong>Sriperumbudur, Oragadam, Ambattur, Guindy, Maraimalai Nagar, Hosur, Ranipet, and Coimbatore</strong>—the Tamil Nadu Pollution Control Board (TNPCB) conducts surprise environmental inspections and rigorous Consent to Operate (CTO) renewal reviews. Non-compliance with on-site storage, manifest loops, or hazardous waste returns exposes industrial units to steep Environmental Compensation fines and immediate factory closure directives.
                    </p>

                    <!-- Key Executive Callout -->
                    <div class="gw-callout-box">
                        <h4><i class="fa fa-gavel" style="color:var(--gw-primary);"></i> The Zero-Tolerance Inspection Mandate</h4>
                        <p>
                            TNPCB District Environmental Engineers (DEEs) inspect industrial units against zero-tolerance parameters: <strong>unmanifested waste oil handovers</strong>, lack of <strong>110% secondary bund containment</strong>, and exceeding the <strong>90-day storage limit</strong>. Fines under CPCB Environmental Compensation guidelines start from ₹30,000 to over ₹1,00,000 per day of ongoing violation.
                        </p>
                    </div>

                    <!-- Section 1 -->
                    <h2 class="gw-h2-title">1. The 90-Day Storage Rule &amp; Storage Yard Engineering</h2>
                    <p>
                        Under <strong>Rule 8</strong> of the <em>Hazardous and Other Wastes (Management and Transboundary Movement) Rules, 2016</em>, manufacturing units are permitted to store accumulated hazardous waste (such as spent oil, oily sludge, and contaminated rags) on-site for a maximum of <strong>90 days</strong>.
                    </p>
                    <p>
                        To satisfy TNPCB physical inspections, your hazardous waste storage shed must comply with strict engineering standards:
                    </p>

                    <div class="gw-checklist-grid">
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-cubes"></i> 1. Impervious Concrete Flooring</h4>
                            <p>Floors must be high-strength reinforced concrete coated with epoxy or chemical-resistant sealant. Unpaved ground, cracked screed, or earthen surfaces constitute immediate violations.</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-shield"></i> 2. 110% Bund Wall Containment</h4>
                            <p>The storage bay must be enclosed by continuous masonry bund walls capable of holding at least 110% of the volume of the largest drum or tank stored, preventing spill migration.</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-umbrella"></i> 3. Weather &amp; Rainwater Protection</h4>
                            <p>The yard must have a sturdy weatherproof roof. No internal rainwater downpipes may discharge into the bund, and zero drains may connect to the municipal storm line.</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-tag"></i> 4. Color-Coded Statutory Labeling</h4>
                            <p>Every drum must carry an indelible fluorescent yellow label marked "HAZARDOUS WASTE" in English and Tamil, stating Waste Category (e.g., Cat 5.1), volume, and accumulation start date.</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-life-ring"></i> 5. Dedicated Spill Response Kits</h4>
                            <p>Store polypropylene absorbent pads, granular absorbent clay, non-sparking shovels, and overpack recovery salvage drums adjacent to the bund gate at all times.</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-eye"></i> 6. Eyewash &amp; Fire Suppression</h4>
                            <p>Install functional emergency eyewash / drench showers and ABC/CO2 dry chemical fire extinguishers within 10 meters of the hazardous waste bay entrance.</p>
                        </div>
                    </div>

