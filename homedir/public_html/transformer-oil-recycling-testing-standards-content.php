                    <!-- Frequently Asked Questions -->
                    <h2 class="gw-h2-title">Frequently Asked Questions (FAQ)</h2>
                    
                    <div class="gw-faq-card">
                        <h4>Q1: What is the minimum acceptable Breakdown Voltage (BDV) for transformer oil under IS 1866?</h4>
                        <p>Under IS 1866, the minimum acceptable BDV for in-service transformer oil depends on the equipment voltage class: for transformers up to 72.5 kV, BDV should be &ge; 30 kV; for 72.5 kV to 145 kV, BDV should be &ge; 40 kV; and for transformers above 145 kV, BDV should be &ge; 50 kV. Recycled oil before refilling is typically restored to &ge; 60 kV.</p>
                    </div>

                    <div class="gw-faq-card">
                        <h4>Q2: Can degraded transformer oil be reconditioned or must it be disposed of?</h4>
                        <p>If degradation is due to moisture, dissolved gases, and carbon, it can be reconditioned via high-vacuum dehydration. If severe chemical oxidation has elevated total acidity above 0.5 mg KOH/g or caused sludge precipitation, the oil must be collected by an authorized recycler (like Green Way Industries) for complete re-refining under CPCB EPR rules.</p>
                    </div>

                    <div class="gw-faq-card">
                        <h4>Q3: What is the permissible PCB (Polychlorinated Biphenyls) limit in recycled transformer oil?</h4>
                        <p>Under MoEF&amp;CC rules and the Stockholm Convention, transformer oil containing PCBs above 50 ppm (mg/kg) is classified as PCB-contaminated hazardous waste and cannot be recycled for general reuse. It must undergo specialized high-temperature destruction.</p>
                    </div>

                    <div class="gw-faq-card">
                        <h4>Q4: What causes the dielectric strength of transformer oil to drop?</h4>
                        <p>The primary causes of BDV decline are moisture ingress from atmospheric humidity or paper insulation degradation, suspended carbon particles from internal micro-arcing, dissolved combustible gases, and polar oxidation byproducts like peroxides and organic acids.</p>
                    </div>

                    <div class="gw-faq-card">
                        <h4>Q5: Does recycling transformer oil generate CPCB EPR certificates?</h4>
