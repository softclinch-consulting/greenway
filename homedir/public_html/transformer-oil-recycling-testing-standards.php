                    <h2 class="gw-h2-title">3. The 5-Step Dielectric Breakdown Voltage (BDV) Test (IS 6792)</h2>
                    <p>
                        Conducting a standardized BDV test ensures precise diagnostic accuracy before determining whether transformer oil can be filtered or must be sent for re-refining:
                    </p>

                    <div class="gw-checklist-grid">
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-flask"></i> 1. Clean Sampling (IS 9435)</h4>
                            <p>Draw oil from the bottom sampling valve after flushing 2-3 liters. Collect in a dry, amber glass bottle shielded from direct sunlight and ambient moisture.</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-crosshairs"></i> 2. 2.5 mm Gap Calibration</h4>
                            <p>Clean test electrodes using residue-free solvent. Use a calibrated feeler gauge to lock the gap precisely at 2.50 mm (&plusmn; 0.05 mm).</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-clock-o"></i> 3. De-Aeration Resting Period</h4>
                            <p>Gently pour the sample along the wall of the test cell to prevent bubbles. Allow the cell to rest undisturbed for 3 to 5 minutes for micro-bubbles to escape.</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-tachometer"></i> 4. Uniform Voltage Rise (2 kV/sec)</h4>
                            <p>Apply AC power frequency voltage starting from zero, ramping at a standardized rate of 2 kV/second (&plusmn; 20%) until spark breakdown occurs.</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-calculator"></i> 5. 6-Strike Average Computation</h4>
                            <p>Perform 6 consecutive breakdowns with a 1-minute settling pause between strikes. Compute the arithmetic mean of strikes 2 through 6 for the certified BDV value.</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-certificate"></i> 6. Pass / Fail Action Protocol</h4>
                            <p>If BDV &ge; 50 kV, oil is sound. If 30-40 kV, schedule vacuum dehydration. If &lt; 30 kV with high acidity, evacuate to Green Way Industries for re-refining.</p>
                        </div>
                    </div>

