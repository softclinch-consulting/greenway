                            Industrial factories and lubricant producers can no longer dispose of used oils through informal, unverified channels. All waste oil handovers must now be executed through <strong>SPCB/TNPCB-authorized recyclers</strong>, tracked via statutory <strong>Form 10 Manifests</strong>, backed by <strong>GST-linked e-invoicing</strong>, and registered on the official <strong>CPCB EPR Portal</strong>.
                        </p>
                    </div>

                    <!-- Section 1 -->
                    <h2 class="gw-h2-title">1. What is the CPCB Used Oil EPR Framework?</h2>
                    <p>
                        In India, millions of liters of used automotive and industrial oils were historically handled by the unorganized sector—often dumped into landfills or burned as polluting fuel in unregulated boilers. According to CPCB environmental audits, <strong>just one liter of unmanaged used oil can contaminate up to 1,000,000 liters of potable water</strong> while emitting carcinogenic heavy metals into the atmosphere.
                    </p>
                    <p>
                        The CPCB EPR mandate establishes a strictly regulated <strong>Circular Economy</strong>. It requires obligated entities to recover and re-refine spent lubricating oils back into virgin-equivalent base oils (Re-Refined Base Oil - RRBO) conforming to Bureau of Indian Standards (BIS) specifications.
                    </p>

