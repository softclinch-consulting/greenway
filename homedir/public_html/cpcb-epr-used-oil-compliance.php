                    <p>
                        State Pollution Control Boards (such as TNPCB in Tamil Nadu) conduct targeted inspections in industrial corridors including Sriperumbudur, Oragadam, Hosur, Ambattur, and Coimbatore. Factories must verify compliance against five specific standards:
                    </p>

                    <div class="gw-checklist-grid">
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-shield"></i> 1. Secondary Containment</h4>
                            <p>Used oil must be stored on an impervious floor surrounded by a containment bund capable of holding 110% of the largest drum volume. Drums must be weather-protected and labeled "HAZARDOUS WASTE - USED OIL".</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-file-text-o"></i> 2. Form 10 Manifests</h4>
                            <p>Every consignment leaving your factory gate must be covered by a 7-copy Form 10 manifest detailing the waste category, volume, transporter details, and designated recycling plant.</p>
                        </div>
                        <div class="gw-checklist-card">
                            <h4><i class="fa fa-truck"></i> 3. GPS Vacuum Tankers</h4>
