                    <!-- Section 5: Integration with Form 3 and Form 4 -->
                    <h2 class="gw-h2-title">5. Connecting Form 10 to Your Form 3 Ledger &amp; Annual Form 4 Returns</h2>
                    <p>
                        A Form 10 manifest does not exist in isolation. It feeds directly into your statutory plant ledger:
                    </p>
                    <ul style="font-size:16px;color:var(--gw-text-muted);padding-left:22px;margin-bottom:30px;">
                        <li style="margin-bottom:12px;"><strong>Form 3 Day-to-Day Register:</strong> Every Form 10 manifest number, date of dispatch, waste category, and net metric weight must be entered into your on-site Form 3 register within 24 hours of dispatch.</li>
                        <li style="margin-bottom:12px;"><strong>Form 4 Annual Return:</strong> On or before <strong>June 30th</strong> of every financial year, your factory must compile the cumulative quantities from your Form 10 manifests into the annual return submitted to TNPCB / SPCB. Discrepancies between total manifest volume and annual return volume prompt automatic audit notices.</li>
                        <li style="margin-bottom:12px;"><strong>5-Year Archive Rule:</strong> Keep all physical manifests organized chronologically in a dedicated fireproof compliance locker for a minimum of 5 years.</li>
                    </ul>

                    <!-- Frequently Asked Questions -->
                    <h2 class="gw-h2-title">Frequently Asked Questions (FAQ)</h2>
                    
                    <div class="gw-faq-card">
                        <h4>Q1: What is Form 10 in hazardous waste management?</h4>
                        <p>Form 10 is a legally binding 7-copy tracking document mandated under Rule 19 of the Hazardous and Other Wastes Rules, 2016. It records the complete cradle-to-grave transfer of hazardous waste from the generator to the authorized transporter and actual-user recycler.</p>
                    </div>

                    <div class="gw-faq-card">
                        <h4>Q2: What are the 7 colors of the Form 10 Manifest and who keeps them?</h4>
                        <p>The 7 copies are: Copy 1 (White - Sender's SPCB); Copy 2 (Yellow - Sender); Copy 3 (Pink - Recycler); Copy 4 (Orange - Transporter); Copy 5 (Green - Recycler's SPCB); Copy 6 (Blue - Sender return); and Copy 7 (Grey - Inter-state SPCB).</p>
                    </div>

                    <div class="gw-faq-card">
                        <h4>Q3: What happens if a factory does not receive the Blue Copy within 30 days?</h4>
                        <p>Under Rule 19(2), if the sender does not receive signed Copy 6 (Blue) within 30 days of dispatch, the factory is legally mandated to report the non-receipt to the State Pollution Control Board. Failure to report makes the factory liable for illegal disposal.</p>
                    </div>

                    <div class="gw-faq-card">
                        <h4>Q4: How long must factories preserve Form 10 manifests for environmental audits?</h4>
                        <p>Factories must maintain physical and digital copies of all Form 10 manifests (especially matching Yellow and Blue copies), alongside Form 3 registers, for a minimum period of 3 to 5 years.</p>
                    </div>

                    <div class="gw-faq-card">
                        <h4>Q5: Can waste oil be transported without a Form 10 manifest?</h4>
                        <p>No. Transporting waste oil or chemical waste without a Form 10 manifest is an illegal offense under the Environment (Protection) Act, resulting in vehicle impoundment, heavy compensation fines, and factory closure orders.</p>
