                    <h2 class="gw-h2-title">3. The 30-Day "Blue Copy" Trap: Why Audits Fail</h2>
                    <p>
                        The most common cause of non-compliance during TNPCB audits in Tamil Nadu industrial corridors (such as Sriperumbudur, Oragadam, Ambattur, and Ranipet) is the <strong>absence of matching Blue Copies</strong>.
                    </p>
                    <div class="gw-callout-box" style="border-left-color: #d32f2f; background: #fff8f8;">
                        <h4 style="color: #b71c1c;"><i class="fa fa-exclamation-triangle"></i> Statutory 30-Day Escalation Mandate (Rule 19(2))</h4>
                        <p style="color: #5d1010;">
                            If the waste generator does not receive the signed <strong>Copy 6 (Blue)</strong> back from the recycling facility within <strong>30 days of shipment</strong>, the generator is legally required to <strong>immediately submit a written report to the State Pollution Control Board</strong>. If an inspection discovers a Yellow Copy without its matching Blue Copy, the board presumes the waste was dumped illegally.
                        </p>
